ORDER = ["select", "hand", "text", "fill", "spray", "brush", "pencil",
         "line", "eraser", "rect", "rectf", "oval", "ovalf", "zoom"]
out = ["; made by icons.py: the tools' 16x16 icons, 2 bytes a row",
       "; order: " + ", ".join(ORDER), "toolicons:"]
for k in ORDER:
    rows = ICONS[k].split("\n")[1:-1]
    assert len(rows) == 16 and all(len(r) == 16 for r in rows), k
    b = []
    for r in rows:
        v = sum(1 << (15 - i) for i, c in enumerate(r) if c == "#")
        b += [v >> 8, v & 255]
    out.append(f"; {k}")
    out.append("        .byte " + ",".join(f"${x:02X}" for x in b[:16]))
    out.append("        .byte " + ",".join(f"${x:02X}" for x in b[16:]))
open("paint_icons.inc", "w").write("\n".join(out) + "\n")
print("paint_icons.inc:", len(ORDER), "icons")
