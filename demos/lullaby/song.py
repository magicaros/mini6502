#!/usr/bin/env python3
"""Writes song.inc: Brahms' Lullaby (Wiegenlied, Op. 49 No. 4, 1868 - public
domain) as three event streams for lullaby.asm.

Each event is 3 bytes: MIDI note (0 = rest), length in ticks (eighth notes),
DUR in frames. A stream ends with $FF. All three streams have the same total
length, so they loop together.

Copyright (C) 2026 Benoit Colson. With the help of Claude AI.
Free software under the GNU General Public License, version 3 or
(at your option) any later version, WITHOUT ANY WARRANTY; see COPYING."""

TICK = 18            # frames per eighth note (keep in step with lullaby.asm)
GAP = 4              # frames of silence at the end of each note

N = dict(C4=60, D4=62, E4=64, F4=65, G4=67, A4=69, B4=71, C5=72)

# melody in 3/4, lengths in eighth notes (6 per bar), with a 2-eighth pickup
melody = """
E4 1 E4 1
G4 4 E4 1 E4 1 | G4 4 E4 1 G4 1 | C5 2 B4 3 A4 1 | A4 2 G4 2 D4 1 E4 1
F4 2 D4 2 D4 1 E4 1 | F4 4 D4 1 F4 1 | B4 1 A4 1 G4 2 B4 2 | C5 4 C4 1 C4 1
C5 4 A4 1 F4 1 | G4 4 E4 1 C4 1 | F4 2 G4 2 A4 2 | G4 4 C4 1 C4 1
C5 4 A4 1 F4 1 | G4 4 E4 1 C4 1 | F4 2 E4 2 D4 2 | C4 6
"""

# one chord per bar: bass note, then two chord tones for the harmony voice
CHORDS = dict(C=(48, 52, 55), F=(41, 57, 60), G=(43, 59, 62), G7=(43, 59, 65))
bars = "C C F G G7 G7 G7 C  F C F C F C G7 C".split()

def ev(note, length, gap=GAP):
    return (note, length, max(1, length * TICK - gap) if note else 0)

mel = []
tok = melody.replace("|", " ").split()
for name, length in zip(tok[0::2], tok[1::2]):
    mel.append(ev(N[name], int(length)))

bass = [ev(0, 2)]                       # silent during the pickup
harm = [ev(0, 2)]
for b in bars:
    root, t1, t2 = CHORDS[b]
    bass.append(ev(root, 6, 10))        # bass on beat 1, held for the bar
    harm += [ev(0, 2), ev(t1, 2), ev(t2, 2)]   # chord tones on beats 2 and 3

for name, s in (("melody", mel), ("bass", bass), ("harmony", harm)):
    total = sum(e[1] for e in s)
    assert total == 2 + 6 * len(bars), (name, total)
    assert all(e[2] <= 255 for e in s)

with open("song.inc", "w") as f:
    f.write("; generated by song.py - Brahms' Lullaby, Op. 49 No. 4 (public domain)\n")
    f.write(f"TICK = {TICK}\n")
    for name, s in (("melody", mel), ("bass", bass), ("harmony", harm)):
        f.write(f"s_{name}:\n")
        for e in s:
            f.write(f"        .byte {e[0]:3d}, {e[1]}, {e[2]:3d}\n")
        f.write("        .byte $FF\n")
print("song.inc:", len(mel), "melody notes,", len(bars), "bars")
