#!/bin/sh
# Native assembler application and its on-demand fixed-RAM core.
# Usage: sh asm/build.sh [output-directory]; requires ca65, ld65, python3.
set -eu
cd "$(dirname "$0")"
out=${1:-build}
mkdir -p "$out"
out=$(cd "$out" && pwd)
ca65 -g -I ../hw -I . asm.asm -o "$out/asm.o"
ld65 -C ../edit/edit.cfg "$out/asm.o" -o "$out/asm.bin" -Ln "$out/asm.labels"
ca65 -g -I ../hw -I . core.asm -o "$out/core.o"
ld65 -C core.cfg "$out/core.o" -o "$out/core.bin" -Ln "$out/core.labels"
python3 ../basic/bin2hex.py "$out/asm.bin" E000 > "$out/asm.hex"
python3 - "$out" <<'PY'
from pathlib import Path
import sys
import re
p = Path(sys.argv[1])
for source, name, address in [('asm.bin', 'ASM', 0xe000), ('core.bin', 'ASMCORE', 0x8400)]:
    body = (p / source).read_bytes()
    (p / name).write_bytes(address.to_bytes(2, 'little') + body)
    print(f'{name}: {len(body)} bytes at ${address:04X}')
(p / 'HELLO.ASM').write_bytes(b'\x00\x04' + Path('hello.asm').read_text().replace('\n', '\r').encode('ascii'))
# The native assembler accepts equates, rather than ca65's conditional guards.
# Derive the disk header from the authoritative generated hardware definitions.
equates = re.findall(r'^([A-Z][A-Z0-9_]*)\s*=\s*(\$[0-9A-F]+|[0-9]+)',
                     Path('../hw/mini6502.inc').read_text(), re.MULTILINE)
hardware = '; mini6502 hardware equates for native ASM; generated by asm/build.sh\n'
hardware += ''.join(f'{name} = {value}\n' for name, value in equates if name != 'MINI6502_INC')
(p / 'hardware.inc').write_text(hardware)
(p / 'HARDWARE.INC').write_bytes(b'\x00\x04' + hardware.replace('\n', '\r').encode('ascii'))
(p / 'INCLUDES.ASM').write_bytes(b'\x00\x04' + Path('include-demo.asm').read_text().replace('\n', '\r').encode('ascii'))
PY
